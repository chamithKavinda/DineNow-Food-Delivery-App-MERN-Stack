import mongoose from 'mongoose';

const userSchema = new mongoose.Schema({
    name: {
        type: String,
        required: true
    },
    email: {
        type: String,
        required: true,
        unique: true
    },
    password: {
        type: String,
        required: true
    },
    cartData: {
        type: Object,
        default: {} // This ensures cartData is always initialized
    }
}, { timestamps: true });

const userModel = mongoose.model('User', userSchema);
export default userModel;